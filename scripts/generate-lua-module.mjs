import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

async function main() {
  const __filename = fileURLToPath(import.meta.url);
  const __dirname = path.dirname(__filename);
  const repoRoot = path.resolve(__dirname, '..');

  const srcLuaDir = path.join(repoRoot, 'src', 'lua');
  const outputFile = path.join(repoRoot, 'src', 'lua', 'scripts.generated.ts');

  const entries = await fs.readdir(srcLuaDir, { withFileTypes: true });
  const luaFiles = entries.filter((e) => e.isFile() && e.name.endsWith('.lua'));

  const scripts = {};
  for (const file of luaFiles) {
    const filePath = path.join(srcLuaDir, file.name);
    const content = await fs.readFile(filePath, 'utf8');
    const scriptName = file.name.replace('.lua', '');
    scripts[scriptName] = content;
  }

  // Generate TypeScript module
  const lines = [
    '// AUTO-GENERATED FILE - DO NOT EDIT',
    '// Generated by scripts/generate-lua-module.mjs',
    '',
    'export const LUA_SCRIPTS: Record<string, string> = {',
  ];

  for (const [name, content] of Object.entries(scripts)) {
    // Escape backticks and ${} in the Lua content for template literals
    const escaped = content
      .replace(/\\/g, '\\\\')
      .replace(/`/g, '\\`')
      .replace(/\$\{/g, '\\${');
    lines.push(`  '${name}': \`${escaped}\`,`);
  }

  lines.push('};');
  lines.push('');

  await fs.writeFile(outputFile, lines.join('\n'), 'utf8');
  console.log(`[generate-lua-module] Generated ${outputFile} with ${luaFiles.length} scripts`);
}

main().catch((err) => {
  console.error('[generate-lua-module] Failed:', err);
  process.exitCode = 1;
});

